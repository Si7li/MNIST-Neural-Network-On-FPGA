from pathlib import Path

import numpy as np

ROOT = Path(__file__).parent.parent
PARAMS = Path(__file__).parent / "out" / "quant_params.npz"
OUT_FILE = ROOT / "src" / "mlp_digits_tb.vhd"
PERIOD_NS = 10


def pixels_hex(image):
    return "".join(format(int(p), "X") for p in reversed(image))


def waveform(signal, values, comments=None, times_ns=None):
    if times_ns is None:
        times_ns = [n * PERIOD_NS for n in range(len(values))]
    lines = []
    for n, value in enumerate(values):
        after = "" if times_ns[n] == 0 else f" after {times_ns[n]} ns"
        end = ";" if n == len(values) - 1 else ","
        note = f"  -- {comments[n]}" if comments else ""
        prefix = f"  {signal} <= " if n == 0 else " " * (len(signal) + 6)
        lines.append(f"{prefix}{value}{after}{end}{note}")
    return lines


def main():
    p = np.load(PARAMS)
    X, labels, expected = p["X_test"], p["y_test"], p["expected_pred"]
    n_images = len(X)

    out = [
        "-- Testbench for the digits network: applies every test image.",
        "-- GENERATED by python/export_testbench.py. Do not edit by hand.",
        "--",
        f"-- Image n is applied at n*{PERIOD_NS} ns ({n_images} images, "
        f"{n_images * PERIOD_NS} ns in total).",
        "--   expected   : the digit the Python model predicts (the hardware must match it)",
        "--   true_label : the correct answer from the dataset",
        "--   match      : '1' when the hardware agrees with the Python model",
        "-- Each pixel is one hex digit; pixel 0 (top-left) is the LAST digit.",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use work.weights_pkg.all;",
        "",
        "entity mlp_digits_tb is",
        "end entity mlp_digits_tb;",
        "",
        "architecture sim of mlp_digits_tb is",
        "  signal pixels     : std_logic_vector(N_IN*PIXEL_W-1 downto 0);",
        "  signal digit      : std_logic_vector(3 downto 0);",
        "  signal hidden     : std_logic_vector(N_HIDDEN*HIDDEN_W-1 downto 0);",
        "  signal scores     : std_logic_vector(N_OUT*ACC2_W-1 downto 0);",
        "  signal image_no   : integer;",
        "  signal expected   : std_logic_vector(3 downto 0);",
        "  signal true_label : std_logic_vector(3 downto 0);",
        "  signal match      : std_logic;",
        "begin",
        "  dut : entity work.mlp_digits",
        "    port map (pixels => pixels, digit => digit, hidden => hidden, scores => scores);",
        "",
        "  match <= '1' when digit = expected else '0';",
        "",
    ]
    out += waveform("image_no", [str(n) for n in range(n_images)])
    out.append("")
    out += waveform("expected", [f'X"{int(d):X}"' for d in expected])
    out.append("")
    out += waveform("true_label", [f'X"{int(d):X}"' for d in labels])
    out.append("")
    out += waveform("pixels", [f'X"{pixels_hex(img)}"' for img in X],
                    [f"image {n}: label {int(labels[n])}" for n in range(n_images)])
    out += ["end architecture sim;", ""]

    OUT_FILE.write_text("\n".join(out))
    print(f"Wrote {OUT_FILE} ({n_images} images, {n_images * PERIOD_NS} ns)")


if __name__ == "__main__":
    main()
