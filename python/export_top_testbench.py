import sys
from pathlib import Path

import numpy as np

from export_testbench import waveform

ROOT = Path(__file__).parent.parent
PARAMS = Path(__file__).parent / "out" / "quant_params.npz"
OUT_FILE = ROOT / "fpga" / "sim" / "nexys3_top_tb.vhd"

CLK_NS = 10
CLKS_PER_BIT = 16
BIT_NS = CLKS_PER_BIT * CLK_NS
BYTE_NS = 10 * BIT_NS
SLOT_BYTES = 80
SLOT_NS = SLOT_BYTES * BYTE_NS
SYNC = 0x80
WARMUP_NS = 1_000
DEFAULT_IMAGES = 20


def uart_levels(byte_stream):
    changes = [(0, 1)]
    for t, byte in byte_stream:
        bits = [0] + [(byte >> b) & 1 for b in range(8)] + [1]
        for n, level in enumerate(bits):
            if level != changes[-1][1]:
                changes.append((t + n * BIT_NS, level))
    return changes


def main():
    n_images = int(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_IMAGES
    p = np.load(PARAMS)
    X, expected = p["X_test"][:n_images], p["expected_pred"][:n_images]

    warmup = [0x41]
    warmup += [SYNC] + list(X[0][:3])
    warmup += [SYNC] + list(X[1][:3]) + [0x55]
    warmup += list(X[1][3:])
    assert len(warmup) <= SLOT_BYTES
    stream = [(WARMUP_NS + n * BYTE_NS, b) for n, b in enumerate(warmup)]

    for n in range(n_images):
        t0 = (n + 1) * SLOT_NS
        frame = [SYNC] + [int(v) for v in X[n]]
        stream += [(t0 + k * BYTE_NS, b) for k, b in enumerate(frame)]

    rx = uart_levels(stream)
    slots = [0] + [(n + 1) * SLOT_NS for n in range(n_images)]

    out = [
        "-- Testbench for the whole board design (nexys3_top): plays the PC side",
        "-- of the USB-UART. GENERATED by python/export_top_testbench.py.",
        "--",
        f"-- UART at {CLKS_PER_BIT} clocks per bit ({BIT_NS} ns) instead of 868, to keep the",
        "-- simulation short. Slot -1 sends input the board must ignore; slot n",
        f"-- ({SLOT_NS} ns each) sends 0x80 + the 64 pixels of test image n.",
        "--   expected : the digit the Python model predicts for this slot's image",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "",
        "entity nexys3_top_tb is",
        "end entity nexys3_top_tb;",
        "",
        "architecture sim of nexys3_top_tb is",
        "  signal clk      : std_logic := '0';",
        "  signal btn_rst  : std_logic;",
        "  signal rxd      : std_logic;",
        "  signal txd      : std_logic;",
        "  signal seg      : std_logic_vector(6 downto 0);",
        "  signal dp       : std_logic;",
        "  signal an       : std_logic_vector(3 downto 0);",
        "  signal led      : std_logic_vector(7 downto 0);",
        "  signal image_no : integer;",
        "  signal expected : std_logic_vector(3 downto 0);",
        "begin",
        "  dut : entity work.nexys3_top",
        f"    generic map (CLKS_PER_BIT => {CLKS_PER_BIT})",
        "    port map (clk => clk, btn_rst => btn_rst, rxd => rxd, txd => txd,",
        "              seg => seg, dp => dp, an => an, led => led);",
        "",
        "  clk     <= not clk after 5 ns;  -- 100 MHz",
        "  btn_rst <= '1', '0' after 100 ns;",
        "",
    ]
    out += waveform("image_no", ["-1"] + [str(n) for n in range(n_images)], times_ns=slots)
    out.append("")
    out += waveform("expected", ['"1111"'] + [f'X"{int(d):X}"' for d in expected],
                    times_ns=slots)
    out.append("")
    out += waveform("rxd", [f"'{level}'" for _, level in rx], times_ns=[t for t, _ in rx])
    out += ["end architecture sim;", ""]

    OUT_FILE.write_text("\n".join(out))
    total_us = (n_images + 1) * SLOT_NS / 1000
    print(f"Wrote {OUT_FILE}: warm-up + {n_images} images, {total_us:.1f} us")


if __name__ == "__main__":
    main()
