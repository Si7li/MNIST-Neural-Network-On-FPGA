from pathlib import Path

import numpy as np

from export_testbench import pixels_hex, waveform

ROOT = Path(__file__).parent.parent
PARAMS = Path(__file__).parent / "out" / "quant_params.npz"
SIM_DIR = ROOT / "fpga" / "sim"
START_NS = 30

CORES = {
    "mlp_seq": (25_000, 24_700),
    "mlp_par32": (2_000, 1_500),
}


def testbench(core, slot_ns, answer_ns, X, labels, expected):
    n_images = len(X)
    tb = f"{core}_tb"
    slots = [n * slot_ns for n in range(n_images)]

    start_values, start_times = ["'0'"], [0]
    for t in slots:
        start_values += ["'1'", "'0'"]
        start_times += [t + START_NS, t + START_NS + 10]

    out = [
        f"-- Testbench for the digits network core {core}: every test image.",
        "-- GENERATED by python/export_seq_testbench.py. Do not edit by hand.",
        "--",
        f"-- 100 MHz clock. Image n gets a {slot_ns // 1000} us slot starting at n*{slot_ns // 1000} us:",
        f"--   +{START_NS} ns: start pulse;",
        f"--   +{answer_ns} ns: expected / true_label switch to this image's answers",
        "--   (the core has updated digit just before).",
        "--   expected   : the digit the Python model predicts (the hardware must match it)",
        "--   true_label : the correct answer from the dataset",
        "--   match      : '1' when the hardware agrees with the Python model",
        "-- Each pixel is one hex digit; pixel 0 (top-left) is the LAST digit.",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use work.mlp_params.all;",
        "",
        f"entity {tb} is",
        f"end entity {tb};",
        "",
        f"architecture sim of {tb} is",
        "  signal clk        : std_logic := '0';",
        "  signal rst        : std_logic;",
        "  signal start      : std_logic;",
        "  signal pixels     : std_logic_vector(N_IN*PIXEL_W-1 downto 0);",
        "  signal busy       : std_logic;",
        "  signal done       : std_logic;",
        "  signal valid      : std_logic;",
        "  signal digit      : std_logic_vector(3 downto 0);",
        "  signal image_no   : integer;",
        "  signal expected   : std_logic_vector(3 downto 0);",
        "  signal true_label : std_logic_vector(3 downto 0);",
        "  signal match      : std_logic;",
        "begin",
        f"  dut : entity work.{core}",
        "    port map (clk => clk, rst => rst, start => start, pixels => pixels,",
        "              busy => busy, done => done, valid => valid, digit => digit);",
        "",
        "  clk   <= not clk after 5 ns;  -- 100 MHz",
        "  rst   <= '1', '0' after 20 ns;",
        "  match <= '1' when digit = expected else '0';",
        "",
    ]
    out += waveform("start", start_values, times_ns=start_times)
    out.append("")
    out += waveform("image_no", [str(n) for n in range(n_images)], times_ns=slots)
    out.append("")
    answer_times = [t + answer_ns for t in slots]
    out += waveform("expected", ['X"0"'] + [f'X"{int(d):X}"' for d in expected],
                    times_ns=[0] + answer_times)
    out.append("")
    out += waveform("true_label", ['X"0"'] + [f'X"{int(d):X}"' for d in labels],
                    times_ns=[0] + answer_times)
    out.append("")
    out += waveform("pixels", [f'X"{pixels_hex(img)}"' for img in X],
                    [f"image {n}: label {int(labels[n])}" for n in range(n_images)],
                    times_ns=slots)
    out += ["end architecture sim;", ""]
    return out


def main():
    p = np.load(PARAMS)
    X, labels, expected = p["X_test"], p["y_test"], p["expected_pred"]
    SIM_DIR.mkdir(parents=True, exist_ok=True)
    for core, (slot_ns, answer_ns) in CORES.items():
        out_file = SIM_DIR / f"{core}_tb.vhd"
        out_file.write_text("\n".join(testbench(core, slot_ns, answer_ns, X, labels, expected)))
        print(f"Wrote {out_file} ({len(X)} images, {len(X) * slot_ns // 1000} us)")


if __name__ == "__main__":
    main()
