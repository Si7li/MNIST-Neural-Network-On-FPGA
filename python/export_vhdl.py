from pathlib import Path

import numpy as np

from data import PIXEL_MAX
from quantize import hardware_widths

ROOT = Path(__file__).parent.parent
PARAMS = Path(__file__).parent / "out" / "quant_params.npz"
OUT_FILE = ROOT / "src" / "weights_pkg.vhd"

WEIGHT_BITS = 8
HIDDEN_BITS = 8
PIXEL_BITS = int(PIXEL_MAX).bit_length()


def bits(value, width):
    value = int(value)
    if not -(2 ** (width - 1)) <= value <= 2 ** (width - 1) - 1:
        raise ValueError(f"{value} does not fit in {width} signed bits")
    return format(value & (2 ** width - 1), f"0{width}b")


def weight_rows(weights, per_line, label):
    lines = []
    for start in range(0, len(weights), per_line):
        chunk = weights[start:start + per_line]
        literals = ", ".join(f'"{bits(w, WEIGHT_BITS)}"' for w in chunk)
        comma = "," if start + per_line < len(weights) else " "
        decimals = " ".join(f"{int(w):4d}" for w in chunk)
        lines.append(f"      {literals}{comma}  -- {label(start)}:{decimals}")
    return lines


def neuron_array(name, type_name, w, per_line, label, comment):
    lines = [f"  -- {comment}", f"  constant {name} : {type_name} := ("]
    for j, row in enumerate(w):
        lines.append(f"    {j} => (  -- neuron {j}")
        lines += weight_rows(row, per_line, label)
        lines.append("    )" + ("," if j < len(w) - 1 else ""))
    lines.append("  );")
    return lines


def bias_array(name, type_name, b, width, comment):
    lines = [f"  -- {comment}", f"  constant {name} : {type_name} := ("]
    for j, v in enumerate(b):
        comma = "," if j < len(b) - 1 else " "
        lines.append(f'    "{bits(v, width)}"{comma}  -- neuron {j}: {int(v)}')
    lines.append("  );")
    return lines


def main():
    p = np.load(PARAMS)
    w1q, b1q, w2q, b2q = p["w1q"], p["b1q"], p["w2q"], p["b2q"]
    n1, n2, s1 = int(p["n1"]), int(p["n2"]), int(p["s1"])
    n_in, n_hidden = w1q.shape
    n_out = w2q.shape[1]
    widths = hardware_widths(w1q, b1q, w2q, b2q)
    acc1_w = widths["acc1_bits_worst_case"]
    acc2_w = widths["acc2_bits_worst_case"]

    out = [
        "-- Weights and biases of the 64 -> 32 -> 10 digits network.",
        "-- GENERATED by python/export_vhdl.py from python/out/quant_params.npz.",
        "-- Do not edit by hand: retrain, then rerun the export script.",
        "--",
        f"-- Weights: {WEIGHT_BITS}-bit two's complement, "
        f"layer 1 Q{8 - n1}.{n1}, layer 2 Q{8 - n2}.{n2}.",
        "-- Biases:  sign-extended to the accumulator width they are added into.",
        "-- W1(j)(i) is the weight from pixel i to hidden neuron j.",
        "-- W2(k)(j) is the weight from hidden neuron j to output neuron k.",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "",
        "package weights_pkg is",
        "  -- Network size",
        f"  constant N_IN     : integer := {n_in};",
        f"  constant N_HIDDEN : integer := {n_hidden};",
        f"  constant N_OUT    : integer := {n_out};",
        "",
        "  -- Bit widths",
        f"  constant PIXEL_W  : integer := {PIXEL_BITS};   -- unsigned pixel 0..{PIXEL_MAX}",
        f"  constant WEIGHT_W : integer := {WEIGHT_BITS};   -- signed weight",
        f"  constant HIDDEN_W : integer := {HIDDEN_BITS};   -- unsigned hidden activation 0..255",
        f"  constant PROD1_W  : integer := {PIXEL_BITS + WEIGHT_BITS};  -- weight x pixel",
        f"  constant PROD2_W  : integer := {HIDDEN_BITS + WEIGHT_BITS};  -- weight x hidden",
        f"  constant ACC1_W   : integer := {acc1_w};  -- layer-1 sum, worst case over any input",
        f"  constant ACC2_W   : integer := {acc2_w};  -- layer-2 sum, worst case over any input",
        f"  constant SHIFT1   : integer := {s1};   -- hidden = min(relu(acc1) >> SHIFT1, 255)",
        "",
        "  -- Types",
        "  subtype weight_t is std_logic_vector(WEIGHT_W-1 downto 0);",
        "  type weight_array is array (natural range <>) of weight_t;",
        "  type w1_t is array (0 to N_HIDDEN-1) of weight_array(0 to N_IN-1);",
        "  type w2_t is array (0 to N_OUT-1) of weight_array(0 to N_HIDDEN-1);",
        "  type b1_t is array (0 to N_HIDDEN-1) of std_logic_vector(ACC1_W-1 downto 0);",
        "  type b2_t is array (0 to N_OUT-1) of std_logic_vector(ACC2_W-1 downto 0);",
        "",
    ]
    out += neuron_array("W1", "w1_t", w1q.T, 8,
                        lambda i: f"image row {i // 8}",
                        "Layer 1 weights: one row per hidden neuron, "
                        "one line per image row")
    out.append("")
    out += bias_array("B1", "b1_t", b1q, acc1_w, "Layer 1 biases")
    out.append("")
    out += neuron_array("W2", "w2_t", w2q.T, 8,
                        lambda i: f"hidden {i:2d}-{i + 7:2d}",
                        "Layer 2 weights: one row per output neuron (digit)")
    out.append("")
    out += bias_array("B2", "b2_t", b2q, acc2_w, "Layer 2 biases")
    out += ["end package weights_pkg;", ""]

    OUT_FILE.write_text("\n".join(out))
    print(f"Wrote {OUT_FILE}")
    print(f"  W1 {n_hidden}x{n_in}, B1 {n_hidden} x {acc1_w} bits, "
          f"W2 {n_out}x{n_hidden}, B2 {n_out} x {acc2_w} bits, SHIFT1 = {s1}")


if __name__ == "__main__":
    main()
